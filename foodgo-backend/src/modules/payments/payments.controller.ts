import {
  BadRequestException,
  Body,
  Controller,
  Get,
  Headers,
  HttpCode,
  HttpStatus,
  Param,
  ParseIntPipe,
  Post,
  Req,
  UnauthorizedException,
  UseGuards,
} from '@nestjs/common';
import { Throttle } from '@nestjs/throttler';
import {
  ApiBearerAuth,
  ApiCreatedResponse,
  ApiHeader,
  ApiOkResponse,
  ApiOperation,
  ApiParam,
  ApiTags,
  ApiUnauthorizedResponse,
} from '@nestjs/swagger';
import { JwtAuthGuard } from '../../common/guards/jwt-auth.guard.js';
import { PaymentsService } from './payments.service.js';
import { CreatePaymentOrderDto } from './dto/create-payment-order.dto.js';
import { VerifyPaymentDto } from './dto/verify-payment.dto.js';
import { PaymentFailureDto } from './dto/payment-failure.dto.js';

function getUserId(req: any): bigint {
  const rawId = req.user?.userId ?? req.user?.sub;
  if (!rawId) throw new UnauthorizedException('User not authenticated');
  return BigInt(rawId);
}

@ApiTags('Payments')
@Controller('payments')
export class PaymentsController {
  constructor(private readonly paymentsService: PaymentsService) {}

  @Throttle({ default: { limit: 20, ttl: 60000 } })
  @Post('create-order')
  @HttpCode(HttpStatus.CREATED)
  @UseGuards(JwtAuthGuard)
  @ApiBearerAuth()
  @ApiOperation({ summary: 'Initiate a server-authoritative payment order' })
  @ApiCreatedResponse({ description: 'Payment order created with gateway' })
  @ApiUnauthorizedResponse({ description: 'Unauthorized' })
  async createPaymentOrder(
    @Req() req: any,
    @Body() dto: CreatePaymentOrderDto,
  ) {
    const userId = getUserId(req);
    return this.paymentsService.createPaymentOrder(userId, dto);
  }

  @Throttle({ default: { limit: 20, ttl: 60000 } })
  @Post('verify')
  @HttpCode(HttpStatus.OK)
  @UseGuards(JwtAuthGuard)
  @ApiBearerAuth()
  @ApiOperation({ summary: 'Verify payment cryptographic signature and confirm order' })
  @ApiOkResponse({ description: 'Payment verified and order confirmed' })
  @ApiUnauthorizedResponse({ description: 'Unauthorized' })
  async verifyPayment(
    @Req() req: any,
    @Body() dto: VerifyPaymentDto,
  ) {
    const userId = getUserId(req);
    return this.paymentsService.verifyPayment(userId, dto);
  }

  @Throttle({ default: { limit: 20, ttl: 60000 } })
  @Post('failure')
  @HttpCode(HttpStatus.OK)
  @UseGuards(JwtAuthGuard)
  @ApiBearerAuth()
  @ApiOperation({ summary: 'Record payment failure or cancellation' })
  @ApiOkResponse({ description: 'Payment failure recorded' })
  @ApiUnauthorizedResponse({ description: 'Unauthorized' })
  async recordFailure(
    @Req() req: any,
    @Body() dto: PaymentFailureDto,
  ) {
    const userId = getUserId(req);
    return this.paymentsService.recordPaymentFailure(userId, dto);
  }

  @Throttle({ default: { limit: 30, ttl: 60000 } })
  @Get('order/:orderId')
  @HttpCode(HttpStatus.OK)
  @UseGuards(JwtAuthGuard)
  @ApiBearerAuth()
  @ApiOperation({ summary: 'Get payment transactions and status for an order' })
  @ApiParam({ name: 'orderId', type: 'number', description: 'Order ID' })
  @ApiOkResponse({ description: 'Order payment details retrieved' })
  @ApiUnauthorizedResponse({ description: 'Unauthorized' })
  async getOrderPayments(
    @Req() req: any,
    @Param('orderId', ParseIntPipe) orderId: number,
  ) {
    const userId = getUserId(req);
    return this.paymentsService.getOrderPayments(userId, orderId);
  }

  @Throttle({ default: { limit: 120, ttl: 60000 } })
  @Post('webhook')
  @HttpCode(HttpStatus.OK)
  @ApiOperation({ summary: 'Razorpay webhook endpoint for asynchronous payment reconciliation' })
  @ApiHeader({
    name: 'x-razorpay-signature',
    description: 'HMAC SHA256 signature generated by Razorpay',
    required: true,
  })
  @ApiHeader({
    name: 'x-razorpay-event-id',
    description: 'Unique event identifier from Razorpay',
    required: false,
  })
  @ApiOkResponse({ description: 'Webhook processed' })
  async handleWebhook(
    @Req() req: any,
    @Headers('x-razorpay-signature') signature: string,
    @Body() body: any,
    @Headers('x-razorpay-event-id') eventIdHeader?: string,
  ) {
    if (!signature) {
      throw new BadRequestException('Missing x-razorpay-signature header');
    }

    const rawBody = req.rawBody
      ? req.rawBody.toString('utf-8')
      : typeof req.body === 'string'
      ? req.body
      : JSON.stringify(req.body);

    let eventData: any;
    try {
      eventData =
        typeof body === 'object' && body !== null
          ? body
          : JSON.parse(rawBody);
    } catch {
      throw new BadRequestException('Malformed webhook JSON payload');
    }

    const headerEventId =
      eventIdHeader ||
      req.headers?.['x-razorpay-event-id'] ||
      req.headers?.['X-Razorpay-Event-Id'];

    return this.paymentsService.handleWebhook(
      signature,
      rawBody,
      eventData,
      headerEventId,
    );
  }
}
